describe('índice público', () => {
  it.each(RUNTIME_EXPORTS)('exporta %s', (name) => {
    expect(vega[name]).toBeDefined();
  });

  it('exporta só a superfície pública', () => {
    expect(Object.keys(vega).sort()).toEqual([...RUNTIME_EXPORTS].sort());
  });

  it('não reexporta a paleta do Atria', () => {
    expect(vega).not.toHaveProperty('paletteFor');
    expect(vega).not.toHaveProperty('artPalettes');
  });

  it('não exporta o Prose, que tem entrada própria', () => {
    expect(vega).not.toHaveProperty('Prose');
  });

  it('exporta os tipos públicos', () => {
    expectTypeOf<PublicTypes>().not.toBeNever();
  });
});
